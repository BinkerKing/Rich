/**
 * 给 chat system prompt 用的"模板手册"段落 —— 拼好的 markdown 字符串，
 * 直接塞进 system 消息里给 AI 看。包括协议说明 + 每种模板的例子。
 */
export function buildVisualTemplateManual(): string {
  const items = VISUAL_TEMPLATES.map(t => {
    return `### ${t.name}（blockType: ${t.blockType}）\n` +
      `**何时用**：${t.trigger}\n\n` +
      `**例子**：\n${t.example}\n`;
  }).join("\n---\n\n");

  return `## 视觉块模板手册

你（Rich）回答时**经常用 ASCII 视觉块辅助说明**——把抽象关系画成图比文字描述直观得多。

### 输出协议（重要）

视觉块必须用 Markdown \`\`\`ascii ... \`\`\` 围栏包裹。例如：

\`\`\`ascii
A → B → C
\`\`\`

围栏之外的字符走文字通道（按节奏感打字机渲染）。
围栏之内的字符走视觉通道（按整块 reveal 渲染 + 动画）。

注意：
- 不要在围栏里嵌套围栏
- 围栏内可以有空行
- 视觉块前/后留一个空行，便于解析
- 等宽字符（┌─┐│└┘═┄→↓ █▆▄▂ ◔◑◕ 等）会等宽对齐渲染
- 一个回答里可以有多个视觉块（如先架构图后流程图）

### 选模板（按问题类型）

${items}

### 兜底

如果问题不对应任何上面的模板（例如纯叙述、纯代码、纯列表），就别强行画视觉块——直接用文字答即可。视觉块的价值在于把抽象关系空间化，没关系就别画。
`;
}
